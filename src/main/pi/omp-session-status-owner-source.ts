// OMP loads the same extension in each in-process task session.
export function getOmpSessionOwnerHandlerSourceLines(): string[] {
  return [
    '  type OmpStatusScopeAllocator = { instance: string; nextOrder: number }',
    '  type OmpStatusSessionProvenance = { manager: object; id?: string; file?: string; parent?: string; retiredManagers?: WeakSet<object>; scopeAllocator?: OmpStatusScopeAllocator }',
    '  let ompStatusInitialized = getOmpNativeRegistry(pi) === null',
    '  let ompStatusSession: OmpStatusSessionProvenance | undefined',
    '',
    '  // SessionManager survives reload/new/resume; task children own a different instance.',
    '  function sessionProvenance(ctx): OmpStatusSessionProvenance | undefined {',
    '    const manager = ctx?.sessionManager',
    "    if (!manager || typeof manager !== 'object') return undefined",
    '    const id = typeof manager.getSessionId === "function" ? manager.getSessionId() : undefined',
    '    const file = typeof manager.getSessionFile === "function" ? manager.getSessionFile() : undefined',
    '    const header = typeof manager.getHeader === "function" ? manager.getHeader() : undefined',
    '    return { manager, id, file, parent: typeof header?.parentSession === "string" ? header.parentSession : undefined }',
    '  }',
    '',
    '  function normalizeSessionPath(file): string {',
    '    const normalized = file.replace(/\\\\/g, "/")',
    '    return /^[A-Za-z]:\\//.test(normalized) ? normalized.toLowerCase() : normalized',
    '  }',
    '',
    '  function isNestedTaskTranscript(parentFile, candidateFile): boolean {',
    '    if (typeof parentFile !== "string" || typeof candidateFile !== "string") return false',
    '    const parent = normalizeSessionPath(parentFile)',
    '    const candidate = normalizeSessionPath(candidateFile)',
    '    const root = parent.endsWith(".jsonl") ? parent.slice(0, -6) : parent',
    '    return candidate.startsWith(`${root}/`) && candidate !== parent',
    '  }',
    '',
    '  function ownsSessionStatus(ctx, name?: string): boolean {',
    '    if (!isOmpRuntime()) return true',
    '    const agentKind = ctx?.agent?.kind ?? ctx?.agentKind',
    '    if (agentKind === "sub" || agentKind === "advisor") return false',
    '    const nativeMain = ctx?.agent?.kind === "main"',
    '    const registry = getOmpNativeRegistry(pi)',
    '    if (registry && !getOmpRegistryRootRef(pi, registry, ctx)) return false',
    '    const current = sessionProvenance(ctx)',
    '    if (!current) return true',
    '    // A native main can fork from another transcript; parentSession alone only',
    '    // rejects children on older runtimes without explicit agent provenance.',
    '    if (current.parent && !nativeMain) return false',
    '    // Keep ownership through module reload and shutdown while child sessions drain.',
    "    const key = Symbol.for('orca.omp.status-session-owners')",
    '    let owners = Reflect.get(globalThis, key)',
    '    if (!(owners instanceof Map)) {',
    '      owners = new Map()',
    '      Reflect.set(globalThis, key, owners)',
    '    }',
    '    const pane = JSON.stringify([process.env.ORCA_PANE_KEY, process.env.ORCA_AGENT_LAUNCH_TOKEN])',
    '    const owner = owners.get(pane)',
    '    if (owner) {',
    '      if (owner.retiredManagers?.has(current.manager)) return false',
    '      current.retiredManagers = owner.retiredManagers',
    '      // Provenance is replaced on every callback; the process scope allocator survives.',
    '      current.scopeAllocator = owner.scopeAllocator',
    '      if (owner.manager !== current.manager) {',
    '        // Only an initializing native root can replace the manager; retired roots cannot reclaim it.',
    '        if (!nativeMain || !registry || (name !== "session_start" && name !== "session_switch" && name !== "session_branch")) return false',
    '        current.retiredManagers ??= new WeakSet<object>()',
    '        current.retiredManagers.add(owner.manager)',
    '      }',
    '    } else if (name === "session_shutdown") return false',
    '    if (registry) current.scopeAllocator ??= { instance: crypto.randomUUID(), nextOrder: 0 }',
    '    owners.set(pane, current)',
    '    ompStatusSession = current',
    '    return true',
    '  }',
    '',
    '  function onStatus(name, handler): void {',
    '    pi.on(name, (event, ctx) => {',
    '      const previousSession = ompStatusSession',
    '      if (!ownsSessionStatus(ctx, name)) return',
    '      lifecycleState.ownsPane = true',
    '      if (isOmpRuntime()) {',
    '        subagentRoster = lifecycleState',
    '        if (!ompStatusInitialized) {',
    '          resetPostQueue()',
    '          ompStatusInitialized = true',
    '        }',
    '        // Only native roots need an implicit scope close; legacy callbacks keep their lifecycle path.',
    '        if (name !== "session_shutdown" && name !== "session_switch" && name !== "session_branch") {',
    '          const currentSession = ompStatusSession',
    '          if (previousSession && currentSession && (previousSession.manager !== currentSession.manager || previousSession.id !== currentSession.id || previousSession.file !== currentSession.file) && getOmpNativeRegistry(pi)) {',
    '            stopOmpRegistryObserver()',
    '            clearPendingAgentEndCheck()',
    '            closeOutRun()',
    '          }',
    '          updateRuntimeOmpSessionMetadata(ctx)',
    '          updateOmpRegistryContext(ctx)',
    '          captureOmpRootStatus(name, event, ctx)',
    '        }',
    '      }',
    '      return handler(event, ctx)',
    '    })',
    '  }'
  ]
}
